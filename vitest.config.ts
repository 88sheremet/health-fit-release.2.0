/*
 * ============================================================
 * OVERVIEW
 * ============================================================
 * Конфигурация Vitest — тестового раннера для юнит- и интеграционных
 * тестов. Тесты лежат в папке tests (паттерн .test.ts) вне SPA-сборки,
 * поэтому для них отдельно настраиваются алиасы и окружение выполнения.
 */
import { defineConfig } from "vitest/config";
import { resolve } from "path";

export default defineConfig({
  /*
   * ============================================================
   * CONFIG: RESOLVE
   * ============================================================
   * Алиас "~" указывает на папку app приложения, как в Nuxt. Без него
   * тесты не смогли бы импортировать код с путями вида ~/stores/...
   */
  resolve: {
    alias: {
      "~": resolve(__dirname, "app"),
    },
  },
  /*
   * ============================================================
   * CONFIG: TEST
   * ============================================================
   *   globals: true   — it/test/expect доступны без импорта;
   *   node            — нода-окружение (не jsdom): DOM-тестов нет,
   *                     а зависимости, требующие браузера, замоканы;
   *   include         — какие файлы считаются тестами;
   *   setupFiles      — ./tests/setup.ts мокает Nuxt-autoimports.
   */
  test: {
    globals: true,
    environment: "node",
    include: ["tests/**/*.test.ts"],
    setupFiles: ["./tests/setup.ts"],
  },
});
