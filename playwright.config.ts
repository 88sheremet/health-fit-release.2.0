/*
 * ============================================================
 * OVERVIEW
 * ============================================================
 * Конфигурация Playwright — раннера end-to-end тестов в папке e2e.
 * Перед прогоном Playwright сам поднимает dev-сервер Nuxt на порту
 * 3100 (webServer ниже) и гоняет тесты против реального браузера
 * Chromium, используя тот же хост, что и в конфигурации.
 */
import { defineConfig } from "@playwright/test";

export default defineConfig({
  /*
   * ============================================================
   * CONFIG: RUN
   * ============================================================
   *   testDir  — где искать e2e-спецификации;
   *   timeout  — лимит на один тест в миллисекундах;
   *   retries  — повторы упавших тестов на CI/локальных прогонах;
   *   expect   — таймауты для expect-проверок (ожидания UI).
   */
  testDir: "e2e",
  timeout: 60_000,
  retries: 2,
  expect: {
    timeout: 20_000,
  },
  /* Глобальная подготовка: мокает Supabase-сеть и готовит фикстуры
   * (запускается один раз до всех тестов на весь прогон). */
  globalSetup: "./e2e/global-setup.ts",
  /*
   * ============================================================
   * CONFIG: BROWSER CONTEXT
   * ============================================================
   * Общие настройки браузерных контекстов: базовый URL, безголовый
   * режим (headless) и прикрепление артефактов только при падении —
   * скриншот страницы и трассировка для разбора ошибок.
   */
  use: {
    baseURL: "http://localhost:3100",
    headless: true,
    screenshot: "only-on-failure",
    trace: "retain-on-failure",
  },
  /* Проекты тестовых окружений. Один проект — десктопный Chromium;
   * другие браузеры можно добавить, не меняя содержимое спецификаций. */
  projects: [{ name: "chromium", use: { browserName: "chromium" } }],
  /*
   * ============================================================
   * CONFIG: WEB SERVER
   * ============================================================
   * Playwright сам запускает Nuxt dev-сервер на порту 3100 перед
   * тестами и ждёт готовности до 120 с. Существующий сервер на этом
   * порту не переиспользуется — стартует строго новый экземпляр.
   */
  webServer: {
    command: "npx nuxt dev --port 3100",
    port: 3100,
    reuseExistingServer: false,
    timeout: 120_000,
  },
});
