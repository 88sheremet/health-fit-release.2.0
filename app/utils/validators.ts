/*
 * ============================================================
 * OVERVIEW
 * ============================================================
 * Переиспользуемая система валидации форм. Отдельные предикаты
 * (isRequired, isEmail, minLength, matchesField) описывают одно
 * простое правило; createValidator склеивает их в композитный
 * валидатор, а validateForm собирает результаты нескольких полей.
 * Сами сообщения об ошибках здесь не хранятся — они передаются
 * вызывающей стороной через i18n-ключ t(...), чтобы текст жил
 * в локализованных файлах (locales/ru.json, uk.json).
 */

/*
 * ============================================================
 * VALIDATORS
 * ============================================================
 */

/* Внутренний шаблон электронной почты: до и после "@" не должно
 * быть пробелов, после точки обязательна хотя бы одна буква. */
const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/* Предикат «поле заполнено»: значение непустое с учётом обрезки
 * пробелов по краям (trim). Используется в login.vue, register.vue
 * и settings.vue как первый шаг проверки каждого поля. */
export const isRequired = (value: string): boolean => value.trim().length > 0;

/* Предикат «корректный email». Сверяет значение с EMAIL_REGEX.
 * Как правило, применяется вторым после isRequired — пустая строка
 * уже отсеялась на первом шаге, на этом проверяем только формат. */
export const isEmail = (value: string): boolean => EMAIL_REGEX.test(value);

/* Фабрика-карри в минимальной длины. Вызов minLength(6) возвращает
 * предикат, который пропускает значение длиной >= min символов.
 * Используется для паролей в register.vue и settings.vue. */
export const minLength =
  (min: number) =>
  (value: string): boolean =>
    value.length >= min;

/* Фабрика сравнения двух полей формы. matchesField(other) сначала
 * фиксирует значение эталонного поля, затем проверяет совпадение.
 * Нужна для подтверждения пароля (register.vue) и нового пароля
 * при его смене (settings.vue). */
export const matchesField =
  (other: string) =>
  (value: string): boolean =>
    value === other;

/*
 * Описание одного правила валидации:
 *   check   — предикат, который должен вернуть true для корректного
 *             значения;
 *   message — i18n-сообщение об ошибке (текст через t(...)), которое
 *             вернётся, если check не прошёл.
 */
export type ValidationRule = {
  check: (value: string) => boolean;
  message: string;
};

/*
 * Композитный валидатор: принимает массив правил и возвращает
 * функцию проверки значения. Логика работы:
 *   1. возвращённая функция вызывается со значением поля;
 *   2. правила перебираются по порядку, строго сверху вниз;
 *   3. при первом же непройденном правиле сразу возвращается его
 *      message — последующие правила уже не проверяются;
 *   4. если все правила дали true, вернётся null (ошибок нет).
 * Пример: createValidator([{check: isRequired, ...},
 *   {check: isEmail, ...}]) сначала отсеивает пустое поле,
 *   а затем проверяет формат адреса.
 */
export function createValidator(rules: ValidationRule[]) {
  return (value: string): string | null => {
    for (const rule of rules) {
      if (!rule.check(value)) return rule.message;
    }
    return null;
  };
}

/*
 * Сборка результата формы: принимает результаты отдельных полей
 * (строка-сообщение об ошибке либо null) и возвращает сообщение
 * первой же ошибки в порядке переданных аргументов. Это позволяет
 * показать пользователю только одну, самую раннюю проблему формы.
 * Возвращает null, когда все поля валидны.
 */
export function validateForm(...results: Array<string | null>): string | null {
  for (const error of results) {
    if (error) return error;
  }
  return null;
}
