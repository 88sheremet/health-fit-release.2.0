/*
 * ============================================================
 * IMPORTS
 * ============================================================
 *
 * routes используется для перенаправления неавторизованных
 * пользователей на страницу входа (/login).
 */
import { routes } from "~/router/routes";

/*
 * ============================================================
 * MIDDLEWARE LOGIC
 * ============================================================
 *
 * Auth-guard: пропускает на страницу только авторизованных пользователей.
 * Подключается через definePageMeta({ middleware: "auth" }) на закрытых
 * страницах приложения, куда без сессии заходить нельзя.
 *
 * Шаги:
 *  1. Получаем текущую сессию Supabase.
 *  2. Ошибка чтения сессии — состояние неизвестно, блокируем переход
 *     и отправляем на /login.
 *  3. Сессии нет — пользователь гость, отправляем на /login.
 *
 * Почему проверяем именно сессию: после выхода или истечения срока
 * действия токена Supabase возвращает null, и только такая проверка
 * позволяет надёжно закрыть гостям доступ к закрытым страницам.
 */
export default defineNuxtRouteMiddleware(async () => {
  const supabase = useSupabaseClient();

  // getSession() читает сессию из локального хранилища Supabase —
  // это главное условие доступа к защищённой странице.
  const {
    data: { session },
    error,
  } = await supabase.auth.getSession();

  if (error) {
    // Ошибка чтения — неизвестное состояние. Нельзя пускать на страницу
    // без уверенности в авторизации, поэтому уходим на вход.
    console.error("[auth middleware] Session error:", error);
    return navigateTo(routes.auth.login);
  }

  if (!session) {
    // null-сессия трактуется как «не авторизован». Гости попадают
    // на страницу входа, а не в закрытую часть приложения.
    return navigateTo(routes.auth.login);
  }
});
