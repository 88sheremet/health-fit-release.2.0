/*
 * ============================================================
 * MIDDLEWARE LOGIC
 * ============================================================
 *
 * Гостевой guard: пропускает на страницу только неавторизованных
 * пользователей. Используется на страницах входа — login.vue подключает
 * его через definePageMeta({ middleware: "guest" }).
 *
 * Если пользователь авторизован, редиректим его в приложение:
 *   - скрининг не пройден -> /welcome (начало онбординга);
 *   - скрининг пройден   -> /daily (главный экран).
 *
 * Это зеркальная пара к auth-middleware: там гостей гонят на /login,
 * здесь — авторизованных прочь от гостевых страниц.
 */
export default defineNuxtRouteMiddleware(async () => {
  const supabase = useSupabaseClient();

  // getUser() делает запрос к серверу Supabase и проверяет токен, —
  // для однозначного ответа «авторизован или нет» этого достаточно.
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    // Пользователь не найден — это гость: пропускаем на гостевую страницу.
    return;
  }

  // Пользователь авторизован: показывать ему форму входа бессмысленно.
  // Уводим его в приложение, предварительно выяснив, прошёл ли он скрининг.
  const { data: screening, error } = await supabase
    .from("screening_results")
    .select("id")
    .eq("user_id", user.id)
    .maybeSingle();

  if (error) {
    // Ошибка проверки скрининга: решение принять нельзя, но и ломать
    // вход не стоит — оставляем пользователя на странице без редиректа.
    console.error("[Guest Middleware] Ошибка проверки screening:", error);

    return;
  }

  if (!screening) {
    // Записи скрининга нет — пользователь новичок: ведём его начинать
    // онбординг со страницы приветствия.
    return navigateTo("/welcome");
  }

  // Скрининг пройден — пользователь уже в основном функционале:
  // отправляем его сразу на главный экран.
  return navigateTo("/daily");
});
