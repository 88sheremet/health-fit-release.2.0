/*
 * ============================================================
 * TYPES
 * ============================================================
 */

/*
 * Тип записи журнала. Соответствует колонке
 * journal_entries.entry_type в Supabase:
 *   "checkin" — ежедневная отметка настроения;
 *   "note"    — свободная заметка пользователя.
 * Используется в stores/journal.ts и страницах журнала.
 */
export type JournalEntryType = "checkin" | "note";

/*
 * ============================================================
 * INTERFACES
 * ============================================================
 */

/*
 * Запись журнала — клиентская модель строки таблицы
 * journal_entries. Объект собирается в mapRowToEntry()
 * стора и потребляется архивом, чек-ином и графиком.
 */
export interface JournalEntry {
  /*
   * Уникальный идентификатор записи.
   * Тип: string (UUID). Колонка БД: journal_entries.id.
   * Используется как :key в списках и для update/delete.
   */
  id: string;

  /*
   * Календарная дата записи.
   * Тип: string (ISO-8601, обычно "YYYY-MM-DD").
   * Колонка БД: journal_entries.date.
   * Основа сортировки архива и проверки «за сегодня».
   */
  date: string;

  /*
   * Вид записи: чек-ин или заметка.
   * Тип: JournalEntryType. Колонка БД: journal_entries.entry_type.
   * На график настроения попадают только строки "checkin".
   */
  type: JournalEntryType;

  /*
   * Настроение по шкале 1 (худшее) .. 5 (лучшее).
   * Тип: 1 | 2 | 3 | 4 | 5, поле необязательное.
   * Колонка БД: journal_entries.mood (NULL у заметок).
   * В UI маппится в эмодзи из constants/moods.ts.
   */
  mood?: 1 | 2 | 3 | 4 | 5;

  /*
   * Текст заметки или комментарий к чек-ину.
   * Тип: string. Колонка БД: journal_entries.note (NULL → "").
   * Отображается в карточках архива и в тултипе графика.
   */
  note: string;
}
