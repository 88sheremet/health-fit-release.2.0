/*
 * Доменная модель задачи дня после мержа базовой строки
 * с её переводом. Используется в сторе tasks, на странице
 * daily.vue и в диалоге TaskDetailsDialog.
 */
export interface Task {
  /* Идентификатор задачи. Соответствует колонке id таблицы daily_tasks. */
  id: string;

  /*
   * Категория задачи. Соответствует колонке type таблицы daily_tasks.
   * Определяет группировку при выборе задач дня и влияет на награду
   * (physical = 15, остальные = 10).
   */
  type: "food" | "mental" | "physical";

  /* Название задачи. Колонка title (или title из daily_task_translations). Отображается в заголовке карточки. */
  title: string;

  /* Награда за выполнение. Колонка reward. Суммируется к energy при completeTask. */
  reward: number;

  /*
   * Инструкция «что делать». Колонка what_doing.
   * Обычно строка, но для физических задач может быть объектом
   * с частями упражнений (back/legs/abs) — обрабатывается в TaskDetailsDialog.
   */
  whatDoing: unknown;

  /* Обоснование «зачем». Колонка why_doing. Отображается в блоке «Почему это важно». */
  whyDoing: string;
}
