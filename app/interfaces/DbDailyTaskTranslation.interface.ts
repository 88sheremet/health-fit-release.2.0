/*
 * Строка таблицы daily_task_translations — локализация задачи.
 * Используется в dailyTask.service.ts для мержа поверх DbDailyTask.
 */
export interface DbDailyTaskTranslation {
  /* Внешний ключ на задачу. Колонка task_id. Ключ в translationMap при мерже. */
  task_id: string;

  /* Язык перевода, например "ru" / "en". Колонка locale. Фильтруется по запрошенному locale. */
  locale: string;

  /* Локализованное название. Колонка title. Заменяет DbDailyTask.title при мерже. */
  title: string;

  /* Локализованная инструкция «что делать». Колонка what_doing. Заменяет одноимённую колонку базовой строки. */
  what_doing: unknown;

  /* Локализованное обоснование «зачем». Колонка why_doing. Заменяет одноимённую колонку базовой строки. */
  why_doing: string;
}
