/* Импорт типа отдельного вопроса для массива questions блока. */
import type { Question } from "./Question.interface";

/*
 * ============================================================
 * ИНТЕРФЕЙС BLOCK — БЛОК ВОПРОСОВ СКРИНИНГА
 * ============================================================
 *
 * Модель одного блока опросника (физика, питание, ментальное
 * здоровье). Используется в статичном массиве SCREENING_BLOCKS
 * хранилища screening.
 */
export interface Block {
  /*
   * Номер блока: 1 — физическое здоровье, 2 — питание,
   * 3 — ментальное здоровье. Является ключом в BlockScores,
   * а также источником доминирующей проблемы (поле
   * dominant_problem в Supabase).
   */
  id: number;
  /*
   * i18n-ключ заголовка блока (screeningBlocks.*.title).
   * Локаль-зависимый: выводится через $t() на странице вопросов.
   */
  title: string;
  /* Массив вопросов блока (по девять вопросов на каждый блок). */
  questions: Question[];
}
