/*
 * Модель записи журнала — тип элементов поля entries ниже.
 */
import type { JournalEntry } from "./JournalEntry.interface";

/*
 * ============================================================
 * INTERFACES
 * ============================================================
 */

/*
 * Состояние Pinia-стора "journal" (stores/journal.ts).
 * Описывает данные, которые возвращает фабрика state().
 */
export interface JournalState {
  /*
   * Все записи пользователя (чек-ины и заметки), хранимые
   * в состоянии и отсортированные по date по возрастанию.
   * Тип: JournalEntry[]. Колонки БД: journal_entries.*.
   * Источник данных для архива и графика настроения.
   */
  entries: JournalEntry[];

  /*
   * Флаг видимости диалога ежедневного чек-ина
   * (компонент CheckInDialog). Тип: boolean.
   * true — за сегодня ещё нет записи типа "checkin".
   * UI-маппинг: управляет v-model модального окна.
   */
  showCheckin: boolean;
}
