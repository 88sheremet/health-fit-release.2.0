/*
 * ============================================================
 * ИНТЕРФЕЙС QUESTION — ВОПРОС СКРИНИНГА
 * ============================================================
 *
 * Модель одного вопроса внутри блока опросника. Используется
 * в статичной конфигурации SCREENING_BLOCKS хранилища screening
 * и на странице questions.vue при отрисовке карточек вопросов.
 */
export interface Question {
  /*
   * Уникальный id вопроса: 101..109 (физика), 201..209 (питание),
   * 301..309 (ментальное здоровье). Используется как ключ
   * в словаре ответов Answers (state.answers).
   */
  id: number;
  /*
   * i18n-ключ текста вопроса, например screeningBlocks.physical.
   * q101. Локаль-зависимый: переводится через $t() на странице
   * вопросов.
   */
  text: string;
}
