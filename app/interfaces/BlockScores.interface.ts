/*
 * ============================================================
 * ИНТЕРФЕЙС BLOCKSCORES — БАЛЛЫ БЛОКОВ СКРИНИНГА
 * ============================================================
 *
 * Словарь суммарных баллов по каждому из трёх блоков опросника.
 * Используется в этом же виде в хранилище screening (state.
 * blockScores) и сохраняется в Supabase отдельными колонками:
 * physical_score, food_score, mind_score.
 */
export interface BlockScores {
  /*
   * Ключ — id блока: 1 — физическое здоровье, 2 — питание,
   * 3 — ментальное здоровье. Значение — сумма ответов на все
   * вопросы соответствующего блока.
   */
  [key: string]: number;
}
