<script setup lang="ts">
/*
 * ============================================================
 * IMPORTS
 * ============================================================
 */

/*
 * Централизованная система маршрутов приложения.
 *
 * Все переходы этой страницы (login / daily / welcome)
 * идут через routes.* вместо хардкода строк.
 */
import { routes } from "~/router/routes";

/*
 * ============================================================
 * DEPENDENCIES
 * ============================================================
 */

/*
 * Клиент Supabase: нужен для проверки сессии пользователя
 * и наличия сохранённого результата скрининга в БД.
 */
const supabase = useSupabaseClient();

/*
 * ============================================================
 * REDIRECT FLOW
 * ============================================================
 *
 * Главная «/» — решает, куда отправить пользователя.
 *
 * 1. supabase.auth.getUser() — текущий пользователь или null.
 * 2. Нет пользователя → routes.auth.login (экран входа).
 * 3. Есть пользователь → читаем строку screening_results
 *    по user_id; maybeSingle() допускает 0 или 1 строку.
 * 4. error запроса → логируем и уводим на welcome, чтобы
 *    не зациклить редирект при временной недоступности БД.
 * 5. Строка найдена (скрининг пройден) → routes.recovery.daily.
 * 6. Строки нет → routes.onboarding.welcome (начать онбординг).
 *
 * Проверка идёт напрямую в БД, а не через screening store:
 * на этапе редиректа store может быть ещё не загружен.
 */

/*
 * Текущая сессия: user либо null, если не авторизован.
 */
const {
  data: { user },
} = await supabase.auth.getUser();

/*
 * Ветвление по результату проверки авторизации.
 */
if (!user) {
  /*
   * Пользователь не залогинен — принудительный переход
   * на страницу входа через централизованный маршрут.
   */
  await navigateTo(routes.auth.login);
} else {
  /*
   * Пользователь залогинен — ищем сохранённый
   * результат скрининга в таблице screening_results.
   */
  const { data: screening, error } = await supabase
    .from("screening_results")
    .select("id")
    .eq("user_id", user.id)
    .maybeSingle();

  if (error) {
    console.error("[Index] Ошибка проверки screening:", error);

    /*
     * Ошибка БД: безопасный fallback в онбординг,
     * чтобы пользователь не «застрял» на главной.
     */
    await navigateTo(routes.onboarding.welcome);
  } else if (screening) {
    /*
     * Скрининг уже пройден — сразу в ежедневный
     * план восстановления.
     */
    await navigateTo(routes.recovery.daily);
  } else {
    /*
     * Записи скрининга нет — начинаем онбординг
     * с приветственного экрана.
     */
    await navigateTo(routes.onboarding.welcome);
  }
}
</script>
