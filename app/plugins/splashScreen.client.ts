/*
 * ============================================================
 * IMPORTS
 * ============================================================
 *
 * Capacitor нужен, чтобы проверить, запущено ли приложение внутри
 * нативной оболочки (isNativePlatform), SplashScreen — чтобы управлять
 * нативной заставкой.
 */
import { Capacitor } from "@capacitor/core";
import { SplashScreen } from "@capacitor/splash-screen";

/*
 * ============================================================
 * PLUGIN LOGIC
 * ============================================================
 *
 * Суффикс `.client.ts` означает, что Nuxt подключит плагин только
 * в браузере: на сервере нет ни WebView, ни нативной заставки.
 *
 * Плагин прячет нативную заставку, когда первая страница уже
 * отрисована. Во время старта приложения код выполняется автоматически
 * (любой файл в папке plugins подключается сам, без ручной регистрации).
 *
 * Шаги:
 *  1. Проверяем, что приложение запущено внутри нативной оболочки
 *     (Capacitor). В вебе заставки нет — выходим сразу.
 *  2. Регистрируем локальную функцию hide(), которая скрывает заставку
 *     и защищена флагом hidden от повторных вызовов.
 *  3. Ставим страховочный таймер на 5 секунд.
 *  4. Навешиваем хук app:suspense:resolve — он срабатывает после
 *     финального рендера первой страницы, тогда и скрываем заставку.
 *
 * Почему скрываем не сразу: в конфиге Capacitor стоит launchAutoHide:
 * false. Иначе заставка исчезала бы вместе с появлением окна приложения,
 * то есть раньше, чем WebView успеет что-то отрисовать, — и между ними
 * пользователь видел бы белый экран.
 */
export default defineNuxtPlugin((nuxtApp) => {
  // В вебе нативной заставки нет — дальше выполнять нечего.
  if (!Capacitor.isNativePlatform()) return;

  // Флаг защищает от двойного вызова hide(): хук и таймер оба могут
  // сработать, а повторный SplashScreen.hide() просто не нужен.
  let hidden = false;

  const hide = () => {
    if (hidden) return;
    hidden = true;
    // Ошибку глушим осознанно: заставка — не тот случай, когда стоит
    // ронять старт приложения.
    SplashScreen.hide().catch(() => {});
  };

  // Страховочный таймер. Если рендер первой страницы упадёт, заставка
  // не должна остаться на экране навсегда — даже экран с ошибкой лучше
  // застывшего логотипа.
  const failsafe = setTimeout(hide, 5000);

  // app:suspense:resolve означает, что первая страница полностью
  // отрисована — теперь заставку можно безопасно скрывать.
  nuxtApp.hook("app:suspense:resolve", () => {
    clearTimeout(failsafe);
    hide();
  });
});
