/*
 * ============================================================
 * ПЕРЕЧИСЛЕНИЕ DOMINANTPROBLEM — ДОМИНИРУЮЩАЯ ПРОБЛЕМА
 * ============================================================
 *
 * Итог скрининга: блок с максимальным суммарным баллом.
 * Значения членов совпадают со значениями dominant_problem
 * в Supabase и с сегментом маршрута результатов в центра-
 * лизованном роутере (routes.results.*). То есть enum исполь-
 * зуется и при хранении в БД, и при редиректе после опросника.
 */
export enum DominantProblem {
  /*
   * Доминирует физический блок (id 1). Ведёт на страницу
   * routes.results.physical (страница физического результата).
   */
  Physical = "physical",

  /* Доминирует блок питания (id 2). Ведёт на routes.results.food. */
  Food = "food",

  /* Доминирует ментальный блок (id 3). Ведёт на routes.results.mind. */
  Mind = "mind",
}
