/*
 * ============================================================
 * OVERVIEW
 * ============================================================
 * Единая карта маршрутов приложения. Ни один путь не зашит в код
 * напрямую: везде используется импорт `routes.<группа>.<ключ>`.
 * Такой подход исключает опечатки, дублирование строк и делает
 * рефакторинг безопасным — достаточно поправить путь здесь.
 *
 * Маршруты сгруппированы по фичам:
 *   onboarding — онбординг пользователя до завершения скрининга;
 *   auth       — вход, регистрация и восстановление пароля;
 *   results    — результаты опроса по трём доменам здоровья;
 *   recovery   — основной recovery-цикл после онбординга;
 *   settings   — единственный экран настроек.
 *
 * Модификатор `as const` сохраняет литеральные типы значений
 * (например, "/login"), поэтому проверки вида `typeof routes.auth.login`
 * остаются строго типизированными для middleware и сервисов.
 * Корректность карты покрыта тестом tests/router/routes.test.ts.
 */

/*
 * ============================================================
 * ROUTE GROUPS
 * ============================================================
 */

/* Онбординг и скрининг. Этап, который пользователь проходит до
 * первого результата: приветствие -> анкета (welcome -> screening ->
 * questions). Потребляют: welcome.vue (кнопка «Начать»), screening.vue
 * (переход к вопросам), login.vue и register.vue (редирект после входа). */
export const routes = {
  onboarding: {
    /* Приглашение к прохождению скрининга. */
    screening: "/screening",
    /* Анкета из блоков вопросов по трём доменам здоровья. */
    questions: "/questions",
    /* Стартовый экран для новых пользователей. */
    welcome: "/welcome",
  },

  /* Аутентификация и работа с паролем. Потребляют: middleware/auth.ts
   * (редирект неавторизованных), LogoutButton.vue, auth/callback.vue
   * (возврат с OAuth), login.vue и register.vue (ссылки друг на друга). */
  auth: {
    /* Вход по почте/паролю или через Google. */
    login: "/login",
    register: "/register",
    forgotPassword: "/forgot-password",
    resetPassword: "/reset-password",
  },

  /* Страницы результатов скрининга. На них questions.vue перенаправляет
   * пользователя после подсчёта баллов в зависимости от доминирующей
   * проблемы; с каждой кнопка ведёт в recovery.daily. */
  results: {
    physical: "/physical-result",
    food: "/food-result",
    mind: "/mind-result",
  },

  /* Основной циклический раздел приложения после завершения онбординга.
   * Потребляют: BottomNavigation.vue (меню сверху-вниз), menu.vue
   * (переключение вкладок), index.vue и login.vue (редирект при наличии
   * скрининга), а также страницы результатов. */
  recovery: {
    /* Сводное меню recovery с выбором дневного/недельного/дневника. */
    menu: "/menu",
    /* Ежедневные задачи. */
    daily: "/daily",
    /* Недельные задачи. */
    weekly: "/weekly",
    /* Дневник настроения и записей. */
    journal: "/journal",
    /* Архив записей дневника. */
    journalArchive: "/journal-archive",
    /* График динамики настроения. */
    journalChart: "/journal-chart",
  },

  /* Экран настроек. Единственный путь без вложенной группы — подгрупп
   * нет, поэтому значение хранится просто строкой. Потребляет
   * authenticated.vue (иконка шестерёнки в шапке). */
  settings: "/settings",
} as const;
